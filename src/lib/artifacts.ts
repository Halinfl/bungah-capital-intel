import { prisma } from "./prisma";

export async function generateIcOnePager(marketSlug: string) {
  const market = await loadMarket(marketSlug);

  const markdown = [
    `# IC One-Pager — ${market.name}`,
    ``,
    `**Product:** Bungah Capital Intel (decision support)`,
    `**As of seed:** public YE 2025 / 2026 stubs`,
    `**Source spine:** ${market.sourceLabel}`,
    ``,
    `## Thesis in one line`,
    ``,
    market.summary,
    ``,
    ...headlineNumbers(market),
    `## Nuance / underwriting rule`,
    ``,
    market.nuanceNote ?? "_No nuance note seeded._",
    ``,
    ...competitiveSet(market),
    ...signalsBlock(market),
    ...findingsBlock(market),
    `## Decision-support next steps`,
    ``,
    `1. Do **not** auto-execute CapEx, outreach, or refinance — human decision required.`,
    `2. Stress submarket + product class, not MSA headline alone.`,
    `3. Pair demand read with talent/GC capacity and debt-wall / DY path.`,
    ``,
    `---`,
    `*Generated by Bungah Capital Intel · build in public · citations required*`,
  ]
    .filter((line) => line !== null)
    .join("\n");

  return prisma.artifact.create({
    data: {
      marketId: market.id,
      kind: "ic-one-pager",
      title: `IC One-Pager — ${market.name}`,
      markdown,
      sourceLabel: market.sourceLabel,
    },
  });
}

