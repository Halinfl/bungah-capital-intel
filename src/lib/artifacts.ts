import { prisma } from "./prisma";
import { citedOnly, citedFindings, coverageInProgressLine, fmtPct, fmtUsd, isNoReadSignal, isSeedMarket } from "./format";
import { parseSourceUrls } from "./source-links";
import { splitTaxSeries } from "./tax-series";
import { buildStackMemo, STACK_MEMO_KIND, type MemoPurpose } from "./stack-memo";

export async function generateIcOnePager(marketSlug: string) {
  const market = await loadMarket(marketSlug);

  const markdown = [
    `# IC One-Pager — ${market.name}`,
    ``,
    `**Product:** Bungah Capital Intel (decision support)`,
    `**Source spine:** ${spine(market)}`,
    ``,
    `## Thesis in one line`,
    ``,
    thesis(market),
    ``,
    ...headlineNumbers(market),
    `## Nuance / underwriting rule`,
    ``,
    (market.seed ? null : market.nuanceNote) ??
      "_Underwrite by submarket and product class, not MSA averages._",
    ``,
    ...competitiveSet(market),
    ...signalsBlock(market),
    ...findingsBlock(market),
    `## Decision-support next steps`,
    ``,
    `1. Do **not** auto-execute CapEx, outreach, or refinance — human decision required.`,
    `2. Stress submarket + product class, not MSA headline alone.`,
    `3. Pair demand read with talent/GC capacity and debt-wall / debt-yield path.`,
    ``,
    `---`,
    `*Generated by Bungah Capital Intel · build in public · citations required*`,
  ]
    .filter((line) => line !== null)
    .join("\n");

  return prisma.artifact.create({
    data: {
      marketId: market.id,
      kind: "ic-one-pager",
      title: `IC One-Pager — ${market.name}`,
      markdown,
      sourceLabel: spine(market),
    },
  });
}

/** Sound Asset Lodging Stack memo — checked Tier 1 market data, deterministic, no LLM. */
export async function generateStackMemo(marketSlug: string, purpose: MemoPurpose = "acquisition") {
  const market = await loadMarket(marketSlug);
  const all = await prisma.signal.findMany({ where: { marketId: market.id }, orderBy: { createdAt: "desc" } });
  const { markdown, tier1 } = buildStackMemo({
    slug: market.slug,
    name: market.name,
    // Tier 1 memos read the full cited set (incl. the whole tax series for the latest print).
    signals: tier1Signals(all, market.signals).filter((s) => !isNoReadSignal(s)),
    purpose,
    snapshot: snapshotRow(market),
  });
  return prisma.artifact.create({
    data: {
      marketId: market.id,
      kind: STACK_MEMO_KIND,
      title: `Sound Asset Lodging — ${market.name}`,
      markdown,
      sourceLabel: tier1 ? "Checked market read · linked original sources" : "Cited signals only · sections not yet checked",
    },
  });
}

/** Cited snapshot row for non-seed markets; links come from the market's own occupancy / visitation rows. */
function snapshotRow(market: LoadedMarket): { t: string; u: string[]; d: string } | null {
  if (market.seed || market.occupancy == null || market.adr == null) return null;
  const u = [
    ...new Set(
      market.signals
        .filter((s) => s.kind === "occupancy" || s.kind === "visitation")
        .flatMap((s) => parseSourceUrls(s.sourceUrls).slice(0, 1).map((l) => l.url))
    ),
  ].slice(0, 2);
  if (!u.length) return null;
  const period = market.sourceLabel.match(/\b(?:YE )?20\d\d\b/)?.[0] ?? "";
  const visitors = market.visitorsM != null ? ` · visitors ${market.visitorsM.toFixed(1)}M` : "";
  return {
    t: `Occupancy ${fmtPct(market.occupancy)} · ADR ${fmtUsd(market.adr, 2)}${visitors}${/\bCBD\b/.test(market.sourceLabel) ? " (CBD)" : ""}`,
    u,
    d: period,
  };
}

function tier1Signals<T extends { id: string }>(all: T[], cited: T[]): T[] {
  const ids = new Set(cited.map((s) => s.id));
  return citedOnly(all as never[]).filter((s: T) => ids.has(s.id) || /^tax-/.test(s.id)) as T[];
}

async function loadMarket(marketSlug: string) {
  const market = await prisma.market.findUnique({
    where: { slug: marketSlug },
    include: {
      assets: true,
      signals: { orderBy: { createdAt: "desc" } },
      findings: {
        include: { radar: true },
        orderBy: { createdAt: "desc" },
        take: 5,
      },
    },
  });
  if (!market) throw new Error(`Market not found: ${marketSlug}`);
  // Seed / illustrative rows and snapshots are never written into an artifact.
  return {
    ...market,
    seed: isSeedMarket(market),
    assets: citedOnly(market.assets),
    // Memos carry the latest four hotel-tax prints, not the full series (that lives on the market page / chat).
    signals: (() => {
      const { other, tax } = splitTaxSeries(citedOnly(market.signals));
      return [...other, ...tax.filter((t) => !/gaps$/.test(t.id)).slice(0, 4)];
    })(),
    findings: citedFindings(market.findings),
  };
}

type LoadedMarket = Awaited<ReturnType<typeof loadMarket>>;

function spine(market: LoadedMarket): string {
  if (!market.seed) return market.sourceLabel;
  const labels = [...new Set(market.signals.map((s) => s.sourceLabel))];
  return labels.length
    ? `Cited Capital Graph rows (${labels.length} sources)`
    : "Cited Capital Graph rows";
}

function thesis(market: LoadedMarket): string {
  return market.seed ? coverageInProgressLine(market.name) : market.summary;
}

function headlineNumbers(market: LoadedMarket): (string | null)[] {
  if (market.seed) return [];
  return [
    `## Headline numbers`,
    ``,
    `| Metric | Value | Source |`,
    `| --- | --- | --- |`,
    `| Visitors | ${market.visitorsM?.toFixed(1) ?? "—"}M | ${market.sourceLabel} |`,
    `| Rooms | ${market.roomsK?.toFixed(1) ?? "—"}k | ${market.sourceLabel} |`,
    `| Occupancy | ${market.occupancy?.toFixed(1) ?? "—"}% | ${market.sourceLabel} |`,
    market.midweekOcc != null
      ? `| Midweek OCC | ${market.midweekOcc.toFixed(1)}% | ${market.sourceLabel} |`
      : null,
    market.weekendOcc != null
      ? `| Weekend OCC | ${market.weekendOcc.toFixed(1)}% | ${market.sourceLabel} |`
      : null,
    `| ADR | $${market.adr?.toFixed(2) ?? "—"} | ${market.sourceLabel} |`,
    ``,
  ];
}

function competitiveSet(
  market: Awaited<ReturnType<typeof loadMarket>>
): string[] {
  return [
    `## Competitive set`,
    ``,
    ...(market.assets.length ? [] : ["_No cited assets yet._"]),
    ...market.assets.map(
      (a) =>
        `- **${a.name}** — ${a.assetClass}${a.keys ? `, ${a.keys} keys` : ""}${a.submarket ? ` · ${a.submarket}` : ""}\n  - ${a.notes ?? ""}\n  - _Source:_ ${a.sourceLabel}`
    ),
    ``,
  ];
}

function signalsBlock(
  market: Awaited<ReturnType<typeof loadMarket>>
): string[] {
  return [
    `## Signals`,
    ``,
    ...(market.signals.length ? [] : ["_No cited signals yet._"]),
    ...market.signals.map(
      (s) =>
        `- **${s.title}** (${s.magnitude ?? "—"}, ${s.asOf ?? "n/a"}) — ${s.body}\n  - _Source:_ ${s.sourceLabel}`
    ),
    ``,
  ];
}

function findingsBlock(
  market: Awaited<ReturnType<typeof loadMarket>>
): string[] {
  return [
    `## Radar findings`,
    ``,
    ...(market.findings.length
      ? market.findings.map(
          (f) =>
            `- **[${f.severity}] ${f.title}** (${f.radar.name}) — ${f.summary}\n  - _Source:_ ${f.sourceLabel}`
        )
      : ["_No market-linked findings._"]),
    ``,
  ];
}
