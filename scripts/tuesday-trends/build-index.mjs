#!/usr/bin/env node
/**
 * Tuesday Trends issue index (runs at the start of every `npm run build`, so it needs no manual step).
 *
 * Scans src/data/tuesday-trends/summary-YYYY-MM-DD*.json and writes src/data/tuesday-trends/issues.generated.ts
 * (and latest.generated.ts, just the dates, for the nav):
 * one static import per issue (the latest summary file per capture date) plus the hotel lists for each issue's
 * list version (src/data/tuesday-trends/lists/<list_version>/*.json). The newest issue drives /tuesday-trends, the
 * home "This Tuesday" card, market pages and Radars; every issue gets a static page at /tuesday-trends/<date>.
 *
 * A new weekly capture only has to commit its summary JSON (and a lists/<version>/ folder when the list changes);
 * the next build picks it up. REIT panel summaries ("panel" set) are skipped. Fails loudly on a malformed or duplicate summary so a bad export never deploys.
 * Usage: node scripts/tuesday-trends/build-index.mjs [--check]   (--check: exit 1 if the committed index is stale)
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const DIR = path.join(ROOT, "src/data/tuesday-trends");
const OUT = path.join(DIR, "issues.generated.ts");
const check = process.argv.includes("--check");

const fail = (msg) => {
  console.error(`tuesday-trends index: ${msg}`);
  process.exit(1);
};

const files = fs.readdirSync(DIR).filter((f) => /^summary-\d{4}-\d{2}-\d{2}.*\.json$/.test(f)).sort();
if (!files.length) fail(`no summary-*.json in ${DIR}`);

/** capture_date -> chosen file. Several files for one date: prefer one with week-over-week, then the newest generated_at. */
const byDate = new Map();
for (const f of files) {
  let j;
  try {
    j = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  } catch (e) {
    fail(`${f} is not valid JSON (${e.message})`);
  }
  // REIT property panel summaries (summary-<date>-reit-panel-*.json, "panel": "reit") are not Tuesday Trends market issues:
  // the REIT pages read src/data/reits/panel-summary.json (scripts/reits/export_panel_summary.py). Skip one that lands here
  // (e.g. a summary-<date>*.json glob copy) instead of failing the build on its missing lists/<reit-panel-...>/ folder.
  if (j.panel) {
    console.warn(`tuesday-trends index: skipping ${f} (panel "${j.panel}" summary, not a market issue)`);
    continue;
  }
  const d = j.capture_date;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d ?? "")) fail(`${f}: capture_date missing or not YYYY-MM-DD`);
  if (!f.startsWith(`summary-${d}`)) fail(`${f}: file name date does not match capture_date ${d}`);
  if (!Array.isArray(j.cells) || !j.cells.length) fail(`${f}: no cells`);
  if (!j.list_version) fail(`${f}: no list_version`);
  const listDir = path.join(DIR, "lists", j.list_version);
  if (!fs.existsSync(listDir)) fail(`${f}: list folder lists/${j.list_version}/ is missing`);
  const cand = { file: f, date: d, listVersion: j.list_version, hasWow: j.wow?.value != null, generatedAt: j.generated_at ?? "" };
  const prev = byDate.get(d);
  if (!prev || (cand.hasWow && !prev.hasWow) || (cand.hasWow === prev.hasWow && cand.generatedAt > prev.generatedAt)) byDate.set(d, cand);
}
const issues = [...byDate.values()].sort((a, b) => b.date.localeCompare(a.date));
const versions = [...new Set(issues.map((i) => i.listVersion))].sort();

const ident = (s) => s.replace(/[^A-Za-z0-9]/g, "_");
const lines = [
  "// GENERATED by scripts/tuesday-trends/build-index.mjs at build time. Do not edit by hand.",
  "// Newest issue first. Add a capture by committing src/data/tuesday-trends/summary-YYYY-MM-DD*.json.",
  "/* eslint-disable */",
];
for (const i of issues) lines.push(`import s_${ident(i.date)} from "./${i.file}";`);
const listImports = [];
for (const v of versions) {
  const lf = fs.readdirSync(path.join(DIR, "lists", v)).filter((f) => f.endsWith(".json")).sort();
  if (!lf.length) fail(`lists/${v}/ has no market lists`);
  listImports.push({ v, names: lf.map((f) => `l_${ident(v)}_${ident(f.replace(/\.json$/, ""))}`) });
  lf.forEach((f, k) => lines.push(`import ${listImports.at(-1).names[k]} from "./lists/${v}/${f}";`));
}
lines.push("");
lines.push("export const TT_LIST_FILES: Record<string, unknown[]> = {");
for (const { v, names } of listImports) lines.push(`  ${JSON.stringify(v)}: [${names.join(", ")}],`);
lines.push("};");
lines.push("");
lines.push("export const TT_ISSUE_FILES: { date: string; file: string; summary: unknown }[] = [");
for (const i of issues) lines.push(`  { date: ${JSON.stringify(i.date)}, file: ${JSON.stringify(i.file)}, summary: s_${ident(i.date)} },`);
lines.push("];");
const text = lines.join("\n") + "\n";

/** Tiny companion (no JSON imports) for the nav, which renders on every page. */
const OUT_LATEST = path.join(DIR, "latest.generated.ts");
const latestText =
  "// GENERATED by scripts/tuesday-trends/build-index.mjs at build time. Do not edit by hand.\n" +
  `export const TT_LATEST_DATE = ${JSON.stringify(issues[0].date)};\n` +
  `export const TT_ISSUE_DATES: string[] = ${JSON.stringify(issues.map((i) => i.date))};\n`;

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
const currentLatest = fs.existsSync(OUT_LATEST) ? fs.readFileSync(OUT_LATEST, "utf8") : "";
if (check) {
  if (current !== text || currentLatest !== latestText) fail("generated index is stale; run node scripts/tuesday-trends/build-index.mjs");
  console.log(`tuesday-trends index up to date: ${issues.length} issues (latest ${issues[0].date})`);
} else {
  if (current !== text) fs.writeFileSync(OUT, text);
  if (currentLatest !== latestText) fs.writeFileSync(OUT_LATEST, latestText);
  console.log(`tuesday-trends index: ${issues.length} issues (latest ${issues[0].date}): ${issues.map((i) => i.date).join(", ")}`);
}
